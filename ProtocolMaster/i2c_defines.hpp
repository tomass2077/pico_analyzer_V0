    struct I2C_DISCOVERY_DEV
    {
        constexpr I2C_DISCOVERY_DEV(const char *c, uint8_t addressMin_, uint8_t addressMax_, uint8_t flag)
            : addressMin(addressMin_), addressMax(addressMax_), addressMode(flag), Name{}
        {
            // Explicitly initialize Name by copying characters and ensuring null termination
            for (size_t i = 0; i < 10 && c[i] != '\0'; ++i)
            {
                Name[i] = c[i];
            }
        }

        bool deviceInAddress(uint8_t address)
        {
            if (address >= addressMin && address <= addressMax)
            {
                if (addressMode == 0)
                    return true;
                if (addressMode == 1 && (address - addressMin) % 2 == 0)
                    return true;
                if (addressMode == 2 && !(address > 23 && address < 64) && !(address > 71 && address < 80))
                    return true;
                if (addressMode == 3 && (address == 45 || address == 83 || address == 87))
                    return true;
            }
            return false;
        }

        char Name[11];
        uint8_t addressMin;
        uint8_t addressMax;
        uint8_t addressMode;
    };
